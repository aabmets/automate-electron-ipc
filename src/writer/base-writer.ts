import fsp from "node:fs/promises";
import path from "node:path";
import type * as t from "@types";
import utils from "../utils.js";
import { ImportsGenerator } from "./imports-generator.js";

/**
 * Replaces the type names of a text of a signature, such as `User` with `User_2`. `refs` are the
 * type references of the whole definition, which the parser took from the AST, and `offset` is
 * the position in the definition where `text` starts. Only the references inside the text are
 * replaced, so names of members, string literals, property keys and parameters stay as written.
 */
function renameTypeReferences(
   text: string,
   offset: number,
   refs: readonly t.TypeRef[],
   renames: ReadonlyMap<string, string>,
): string {
   let result = "";
   let last = 0;
   for (const ref of refs) {
      const renamed = renames.get(ref.name);
      if (renamed !== undefined && ref.start >= offset + last && ref.end <= offset + text.length) {
         result += text.slice(last, ref.start - offset) + renamed;
         last = ref.end - offset;
      }
   }
   return result + text.slice(last);
}
/** The `maxQueue` of a port channel which does not set it: how many messages a send queue holds. */
export const DEFAULT_MAX_QUEUE = 1000;

const IDENTIFIER_PATTERN = /^[A-Za-z_$][\w$]*$/;
const IDENTIFIER_TOKENS = /[A-Za-z_$][\w$]*/g;

export class BaseWriter {
   protected config: t.IPCResolvedConfig;
   protected pfsArray: t.ParsedFileSpecs[];
   protected importsGenerator: ImportsGenerator;
   protected indents: string[];
   protected notice = utils
      .dedent(`
         // NOTICE: THIS FILE WAS GENERATED BY AUTOMATE-ELECTRON-IPC.
         // ANY CHANGES TO THIS FILE WILL NOT PERSIST BETWEEN GENERATIONS.
      `)
      .trim();

   public constructor(config: t.IPCResolvedConfig, pfsArray: t.ParsedFileSpecs[]) {
      if (this.constructor === BaseWriter) {
         throw new Error(`Cannot instantiate abstract base class '${this.constructor.name}'`);
      }
      this.config = config;
      this.pfsArray = pfsArray;
      this.importsGenerator = new ImportsGenerator(
         config.projectUsesNodeNext,
         this.getTargetFilePath(),
         this.getReservedNames(),
      );
      this.indents = this.getCodeIndents();
   }

   private throwAbstractError(methodName: string): void {
      throw new Error(`Must implement method '${methodName}' in '${this.constructor.name}' class`);
   }

   protected getTargetFilePath(): string {
      this.throwAbstractError("getTargetFilePath");
      return null as unknown as string;
   }

   /** The names that the generated file declares or imports, which schema types must not take. */
   protected getReservedNames(): string[] {
      return [];
   }

   /** Whether the file has nothing to declare, which is written as the empty file. */
   protected isEmpty(): boolean {
      return this.pfsArray.length === 0;
   }

   protected renderEmptyFileContents(): string {
      this.throwAbstractError("renderEmptyFileContents");
      return null as unknown as string;
   }

   protected renderFileContents(): string {
      this.throwAbstractError("generateFileContents");
      return null as unknown as string;
   }

   /**
    * The channel name that Electron sees, as a quoted literal: the name of the channel in the
    * schema behind `channelPrefix`. Hooks and errors keep the name from the schema. `suffix` names
    * a second wire channel of the same schema channel, such as `:reply`. A schema channel name is
    * an identifier, so a name with a colon cannot be the wire name of another channel.
    */
   protected wireName(name: string, suffix = ""): string {
      return `'${this.config.channelPrefix ?? ""}${name}${suffix}'`;
   }

   /** The name that the API is exposed as in the page. */
   protected getExposeAs(): string {
      return this.config.exposeAs ?? "ipc";
   }

   /** Whether the preload script exposes the API itself, as it loads. */
   protected getAutoExpose(): boolean {
      return this.config.autoExpose ?? true;
   }

   /**
    * The time after which an `invoke` channel rejects with an `IpcTimeoutError`: the option of the
    * channel, or else the default of the config. `0` means no timeout.
    */
   protected getTimeoutMs(spec: t.ChannelSpec): number {
      return spec.timeoutMs ?? this.config.timeoutMs ?? 0;
   }

   /** Whether the channel is between the main process and a utility process. */
   protected isUtilitySpec(spec: t.ChannelSpec): boolean {
      return spec.direction === "MainToUtility" || spec.direction === "UtilityToMain";
   }

   /**
    * Whether the channel is between a renderer and a utility process, over a port which the main
    * process brokers. The page uses it like the other channels of a renderer.
    */
   protected isBrokeredSpec(spec: t.ChannelSpec): boolean {
      return spec.direction === "RendererToUtility";
   }

   /** Whether any schema file declares a channel that a utility process takes part in. */
   protected hasUtilityChannels(): boolean {
      return this.pfsArray.some((pfs) =>
         pfs.specs.channelSpecArray.some(
            (spec) => this.isUtilitySpec(spec) || this.isBrokeredSpec(spec),
         ),
      );
   }

   /** The channels of a schema file that a renderer takes part in. */
   protected getRendererSpecs(parsedFileSpecs: t.ParsedFileSpecs): t.ChannelSpec[] {
      return parsedFileSpecs.specs.channelSpecArray.filter((spec) => !this.isUtilitySpec(spec));
   }

   /** Whether any schema file declares a channel that a renderer takes part in. */
   protected hasRendererChannels(): boolean {
      return this.pfsArray.some((pfs) => this.getRendererSpecs(pfs).length > 0);
   }

   protected getCodeIndents(): string[] {
      return [1, 2, 3, 4, 5, 6].map((value) => {
         return " ".repeat(this.config.codeIndent).repeat(value);
      });
   }

   /**
    * The channel specs of a schema file, with the type names of their signatures replaced by
    * the names that the generated imports declare (see `ImportsGenerator.getRenames`).
    */
   protected getChannelSpecs(parsedFileSpecs: t.ParsedFileSpecs): t.ChannelSpec[] {
      const specs = parsedFileSpecs.specs.channelSpecArray;
      const renames = this.importsGenerator.getRenames(parsedFileSpecs);
      if (renames.size === 0) {
         return specs;
      }
      return specs.map((spec) => {
         const { definition, paramsStart, returnType, returnStart, params, chunkType, chunkStart } =
            spec.signature;
         const refs = spec.signature.typeRefs ?? [];
         const rename = (text: string, offset: number | undefined) =>
            offset === undefined ? text : renameTypeReferences(text, offset, refs, renames);
         const errors = spec.errors && {
            ...spec.errors,
            definition: renameTypeReferences(
               spec.errors.definition,
               0,
               spec.errors.typeRefs ?? [],
               renames,
            ),
            typeRefs: [],
         };
         return {
            ...spec,
            ...(errors ? { errors } : {}),
            signature: {
               ...spec.signature,
               definition: rename(definition, 0),
               // Renaming changes the length of the text before the parameter list.
               paramsStart: rename(definition.slice(0, paramsStart), 0).length,
               returnType: rename(returnType, returnStart),
               ...(chunkType === undefined ? {} : { chunkType: rename(chunkType, chunkStart) }),
               params: params.map((param) => ({
                  ...param,
                  type: rename(param.type, param.typeStart),
               })),
               // The offsets of the references refer to the text before the renaming.
               typeRefs: [],
            },
         };
      });
   }

   /**
    * Inserts the event parameter at the start of the parameter list of the signature.
    * The position comes from the parser, since the first `(` of the text can belong to
    * the type parameters, as in `<T extends (x: number) => void>(cb: T) => void`.
    */
   protected injectEventTypehint(
      signature: t.CallableSignature,
      eventType: string,
      eventName = "event",
   ): string {
      const { definition, paramsStart, params } = signature;
      const separator = params.length > 0 ? ", " : "";
      return [
         definition.slice(0, paramsStart),
         `${eventName}: ${eventType}${separator}`,
         definition.slice(paramsStart),
      ].join("");
   }

   /**
    * Returns the type parameters of the signature, such as `<T extends Foo>`, or an empty
    * string. Generated functions repeat them so that the
    * parameter types which refer to them stay valid.
    */
   protected getTypeParams(signature: t.CallableSignature): string {
      return signature.definition.slice(0, signature.paramsStart - 1).trim();
   }

   /**
    * Returns the parameters of the channel signature with names that are valid identifiers.
    * Destructured parameters, such as `{ a, b }: Foo`, cannot be forwarded by name,
    * so they are replaced by generated names that clash with no name in the signature.
    */
   protected resolveParams(spec: t.ChannelSpec): t.CallableParam[] {
      const params = spec.signature.params;
      const taken = this.collectIdentifiers(params.map((param) => param.name));
      return params.map((param, index) => {
         if (IDENTIFIER_PATTERN.test(param.name)) {
            return param;
         }
         return { ...param, name: this.uniqueName(`arg${index}`, taken) };
      });
   }

   /** The `maxQueue` of a port channel as source text: a number, or `Infinity`. */
   protected getMaxQueue(spec: t.ChannelSpec): string {
      return String(spec.maxQueue ?? DEFAULT_MAX_QUEUE);
   }

   protected getOriginalParams(spec: t.ChannelSpec, onlyNames: boolean): string {
      return this.resolveParams(spec)
         .map((param) => {
            const rest = param.rest ? "..." : "";
            if (onlyNames) {
               return `${rest}${param.name}`;
            }
            const optional = param.optional ? "?" : "";
            return `${rest}${param.name}${optional}: ${param.type || "any"}`;
         })
         .join(", ");
   }

   /**
    * Collects every identifier-like token of the given source snippets.
    * Names that are absent from the result cannot clash with anything in the snippets.
    */
   protected collectIdentifiers(snippets: string[]): Set<string> {
      return new Set(snippets.flatMap((snippet) => snippet.match(IDENTIFIER_TOKENS) ?? []));
   }

   /**
    * Returns `base`, with underscores prepended until it is absent from `taken`,
    * and adds the result to `taken`.
    */
   protected uniqueName(base: string, taken: Set<string>): string {
      let name = base;
      while (taken.has(name)) {
         name = `_${name}`;
      }
      taken.add(name);
      return name;
   }

   /**
    * Sorts the channels by name, in code unit order, so that the output does not depend on
    * the locale: `getFoo` comes before `getFoo2`, and upper case before lower case.
    */
   protected sortChannels<T extends { name: string }>(channels: T[]): T[] {
      return channels.sort((a, b) => utils.compareStrings(a.name, b.name));
   }

   public async write(withNotice = true) {
      const targetFilePath = this.getTargetFilePath();
      const fileDirectory = path.dirname(targetFilePath);
      await fsp.mkdir(fileDirectory, { recursive: true });
      let contents: string;
      if (this.isEmpty()) {
         contents = this.renderEmptyFileContents();
      } else {
         contents = this.renderFileContents();
      }
      // The file starts with its first line, not with a blank one.
      contents = contents.replace(/^\n+/, "");
      if (withNotice) {
         contents = `${this.notice}\n\n${contents}`;
      }
      await fsp.writeFile(targetFilePath, contents);
   }
}
